# Oracle-mode sequence options (CACHE, SCALE, EXTEND, SESSION) and
# Oracle-style identity columns survive a dump and restore through either
# port.  Their Oracle-only parts are written to a TOC entry of their own,
# which pg_restore runs through the Oracle grammar.

use strict;
use warnings FATAL => 'all';

use PostgreSQL::Test::Cluster;
use PostgreSQL::Test::Utils;
use Test::More;

my $node = PostgreSQL::Test::Cluster->new('sequence_identity');
$node->init;
$node->start;
my $tempdir = PostgreSQL::Test::Utils::tempdir;

$node->safe_psql('postgres', 'CREATE DATABASE seq_source');
$node->safe_psql(
	'seq_source',
	q{
CREATE SEQUENCE s_cache20;
CREATE SEQUENCE s_nocache START WITH 5 INCREMENT BY 2 NOCACHE;
CREATE SEQUENCE s_scale SCALE EXTEND;
CREATE SEQUENCE s_session MAXVALUE 99999 CYCLE SCALE NOEXTEND SESSION;
CREATE SEQUENCE s_noextend_max MAXVALUE 9999999999999 SCALE NOEXTEND;
SELECT s_nocache.nextval FROM dual;
CREATE SEQUENCE s_number AS number START WITH 10 CACHE 5;
CREATE SEQUENCE s_numeric_desc AS numeric INCREMENT BY -1;
CREATE SEQUENCE s_float8 AS double precision NOCACHE;
SELECT s_number.nextval FROM dual;
SELECT s_numeric_desc.nextval FROM dual;
CREATE TABLE ora_always (id int GENERATED ALWAYS AS IDENTITY, v int);
CREATE TABLE ora_default (
  id int GENERATED BY DEFAULT AS IDENTITY (START WITH 100 INCREMENT BY 10),
  v int);
CREATE TABLE ora_on_null (
  id int GENERATED BY DEFAULT ON NULL AS IDENTITY (START WITH 3 SCALE EXTEND),
  v int);
CREATE TABLE ora_unlogged_seq (id int GENERATED ALWAYS AS IDENTITY, v int);
ALTER SEQUENCE ora_unlogged_seq_id_seq SET UNLOGGED;
INSERT INTO ora_always (v) VALUES (1), (2);
INSERT INTO ora_default (v) VALUES (1);
INSERT INTO ora_on_null (id, v) VALUES (NULL, 1);
},
	connect_to_oraport => 1);

my $catalog_query = q{
SELECT c.relname, c.relpersistence, s.seqtypid::regtype, s.seqstart, s.seqincrement,
       s.seqmax, s.seqmin, s.seqcache, s.seqcycle, s.flags, q.last_value
FROM pg_catalog.pg_sequence s
JOIN pg_catalog.pg_class c ON c.oid = s.seqrelid
JOIN pg_catalog.pg_sequences q
  ON q.schemaname = 'public' AND q.sequencename = c.relname
ORDER BY c.relname;
SELECT a.attrelid::regclass, a.attname, a.atttypid::regtype, a.attidentity,
       a.attnotnull, pg_catalog.pg_get_serial_sequence(a.attrelid::regclass::text, a.attname)
FROM pg_catalog.pg_attribute a
JOIN pg_catalog.pg_class c ON c.oid = a.attrelid
WHERE c.relnamespace = 'public'::regnamespace AND c.relkind = 'r'
  AND a.attnum > 0 AND NOT a.attisdropped
ORDER BY 1, 2;
SELECT 'ora_always', * FROM ora_always
UNION ALL SELECT 'ora_default', * FROM ora_default
UNION ALL SELECT 'ora_on_null', * FROM ora_on_null
ORDER BY 1, 2;
};
my $expected_catalog = $node->safe_psql('seq_source', $catalog_query);

like($expected_catalog, qr/^s_scale\|.*\|2064\|/m,
	'source has a SCALE EXTEND sequence');

for my $port ($node->port, $node->oraport)
{
	my $mode = $port == $node->oraport ? 'Oracle' : 'PostgreSQL';

	for my $format ('plain', 'custom')
	{
		my $dump = "$tempdir/seq_${port}_$format";
		my $label = "$format dump and restore through the $mode port";
		$node->command_ok(
			[
				'pg_dump', "--port=$port", '--dbname=seq_source',
				"--format=$format", "--file=$dump", '--no-sync'
			],
			"$format dump through the $mode port");

		if ($format eq 'plain')
		{
			my $text = slurp_file($dump);

			# NOCACHE stands for a cache of 1 only.
			like($text,
				qr/CREATE SEQUENCE public\.s_cache20\n(?:    .*\n)*    CACHE 20;/,
				"$label keeps a cache of 20");
			like($text, qr/^ALTER SEQUENCE public\.s_scale SCALE EXTEND;$/m,
				"$label writes SCALE EXTEND");
			like($text,
				qr/^ALTER SEQUENCE public\.s_session SCALE NOEXTEND SESSION;$/m,
				"$label writes SCALE NOEXTEND SESSION");
			like($text,
				qr/^ALTER TABLE public\.ora_always MODIFY id GENERATED ALWAYS AS IDENTITY;$/m,
				"$label writes the kind of an Oracle-style identity");
			unlike($text, qr/^CREATE TABLE[^;]*GENERATED[^;]*AS IDENTITY/m,
				"$label attaches identities after the table is created");
			like($text, qr/CREATE SEQUENCE public\.s_number\n    AS sys\.number\n/,
				"$label keeps the NUMBER type of a sequence");
			if ($port == $node->port)
			{
				like($text,
					qr/^DO '.*\n(?:.*\n)*?    EXECUTE ''CREATE SEQUENCE public\.s_number\n/m,
					"$label creates a NUMBER sequence in Oracle mode");
			}
		}

		my $dbname = "restore_${port}_$format";
		$node->safe_psql('postgres', "CREATE DATABASE $dbname");
		if ($format eq 'plain')
		{
			$node->command_ok(
				[
					'psql', '-X', "--port=$port", "--dbname=$dbname",
					'--set=ON_ERROR_STOP=1', '--single-transaction',
					"--file=$dump"
				],
				$label);
		}
		else
		{
			$node->command_ok(
				[
					'pg_restore', "--port=$port", "--dbname=$dbname",
					'--exit-on-error', '--single-transaction', $dump
				],
				$label);
		}

		is($node->safe_psql($dbname, $catalog_query),
			$expected_catalog,
			"$label preserves sequences, identity columns and their data");

		# Each identity keeps generating values the way its kind requires.
		is( $node->safe_psql(
				$dbname, q{
INSERT INTO ora_always (v) VALUES (3);
INSERT INTO ora_default (v) VALUES (2);
INSERT INTO ora_default (id, v) VALUES (7, 3);
INSERT INTO ora_on_null (id, v) VALUES (NULL, 2);
SELECT count(DISTINCT id) FROM ora_always;
SELECT count(DISTINCT id) FROM ora_default;
SELECT count(*) FROM ora_on_null WHERE id IS NULL;
},
				connect_to_oraport => 1),
			"3\n3\n0",
			"$label keeps identity columns generating values");
		my ($ret, $stdout, $stderr) = $node->psql($dbname,
			'INSERT INTO ora_always (id, v) VALUES (99, 4)',
			connect_to_oraport => 1);
		is($ret, 3, "$label fails an explicit value for an ALWAYS identity");
		like($stderr,
			qr/cannot insert a generated always identity column "id"/,
			"$label keeps an ALWAYS identity refusing explicit values");
	}
}

# A selective restore of a sequence brings its Oracle-only options along.
$node->safe_psql('postgres', 'CREATE DATABASE selective_restore');
$node->command_ok(
	[
		'pg_restore', '--port=' . $node->port, '--dbname=selective_restore',
		'--exit-on-error',
		'--table=s_scale', '--table=s_session',
		'--table=ora_always', '--table=ora_always_id_seq',
		"$tempdir/seq_" . $node->port . '_custom'
	],
	'selective restore of sequences and an identity column');
is( $node->safe_psql(
		'selective_restore', q{
SELECT c.relname, s.flags FROM pg_catalog.pg_sequence s
JOIN pg_catalog.pg_class c ON c.oid = s.seqrelid
WHERE c.relnamespace = 'public'::regnamespace
ORDER BY 1;
SELECT attidentity FROM pg_catalog.pg_attribute
WHERE attrelid = 'ora_always'::regclass AND attname = 'id';
}),
	"ora_always_id_seq|0\ns_scale|2064\ns_session|80\ni",
	'selective restore keeps SCALE, EXTEND, SESSION and the identity kind');

done_testing();
