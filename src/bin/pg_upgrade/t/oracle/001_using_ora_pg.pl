# Upgrade an Oracle-mode cluster that holds packages and object types, both
# through the Oracle port (the default) and through the PostgreSQL port
# (--using-ora-pg), and check that every object arrives intact.

use strict;
use warnings FATAL => 'all';

use PostgreSQL::Test::Cluster;
use PostgreSQL::Test::Utils;
use Test::More;

my $old = PostgreSQL::Test::Cluster->new('old');
$old->init;
$old->start;

$old->safe_psql(
	'postgres',
	q{
CREATE SCHEMA "MixSch";
CREATE ROLE pkg_owner;
CREATE ROLE pkg_user;
CREATE OR REPLACE PACKAGE "MixSch"."MixPkg" AS
  FUNCTION hello RETURN varchar2;
END;
/
CREATE OR REPLACE PACKAGE BODY "MixSch"."MixPkg" AS
  FUNCTION hello RETURN varchar2 IS
  BEGIN
    RETURN 'hello from MixPkg';
  END;
END;
/
ALTER PACKAGE "MixSch"."MixPkg" OWNER TO pkg_owner;
COMMENT ON PACKAGE "MixSch"."MixPkg" IS 'mixed-case package';
GRANT EXECUTE ON PACKAGE "MixSch"."MixPkg" TO pkg_user;
REVOKE ALL ON PACKAGE sys.dbms_random FROM PUBLIC;
ALTER DEFAULT PRIVILEGES IN SCHEMA "MixSch" GRANT EXECUTE ON PACKAGES TO pkg_user;
CREATE OR REPLACE PACKAGE spec_only AS
  answer CONSTANT integer := 42;
END;
/
CREATE TYPE obj_t AS OBJECT (
  id integer,
  MEMBER FUNCTION doubled RETURN integer,
  MEMBER FUNCTION tripled RETURN integer);
/
CREATE TYPE attr_t AS OBJECT (
  a_ora_date date,
  a_pg_date pg_catalog.date,
  a_ts timestamp,
  a_pg_ts pg_catalog.timestamp,
  a_varchar2 varchar2(10),
  a_pg_varchar pg_catalog.varchar(10),
  a_number number(5,2),
  a_pg_numeric pg_catalog.numeric(5,2));
/
CREATE TYPE BODY obj_t AS
  MEMBER FUNCTION doubled RETURN integer IS
  BEGIN
    RETURN self.id * 2;
  END;
  MEMBER FUNCTION tripled RETURN integer IS
  BEGIN
    RETURN self.id * 3;
  END;
END;
/
CREATE TABLE obj_tab (k integer, o obj_t);
INSERT INTO obj_tab VALUES (1, obj_t(21));
CREATE TABLE attr_tab (a attr_t);
INSERT INTO attr_tab VALUES (attr_t(DATE '2026-11-16', DATE '2026-11-16',
  TIMESTAMP '2026-11-16 10:00:00', TIMESTAMP '2026-11-16 10:00:00',
  'abc', 'abc', 1.25, 1.25));
CREATE SEQUENCE s_cache20;
CREATE SEQUENCE s_nocache START WITH 5 INCREMENT BY 2 NOCACHE;
CREATE SEQUENCE s_scale SCALE EXTEND;
CREATE SEQUENCE s_session MAXVALUE 99999 CYCLE SCALE NOEXTEND SESSION;
CREATE SEQUENCE s_noextend_max MAXVALUE 9999999999999 SCALE NOEXTEND;
SELECT s_nocache.nextval FROM dual;
CREATE SEQUENCE s_number AS number START WITH 10 CACHE 5;
CREATE SEQUENCE s_numeric_desc AS numeric INCREMENT BY -1;
CREATE SEQUENCE s_float8 AS double precision NOCACHE;
SELECT s_number.nextval FROM dual;
SELECT s_numeric_desc.nextval FROM dual;
CREATE TABLE ora_always (id int GENERATED ALWAYS AS IDENTITY, v int);
CREATE TABLE ora_default (
  id int GENERATED BY DEFAULT AS IDENTITY (START WITH 100 INCREMENT BY 10),
  v int);
CREATE TABLE ora_on_null (
  id int GENERATED BY DEFAULT ON NULL AS IDENTITY (START WITH 3 SCALE EXTEND),
  v int);
CREATE TABLE ora_unlogged_seq (id int GENERATED ALWAYS AS IDENTITY, v int);
ALTER SEQUENCE ora_unlogged_seq_id_seq SET UNLOGGED;
INSERT INTO ora_always (v) VALUES (1), (2);
INSERT INTO ora_default (v) VALUES (1);
INSERT INTO ora_on_null (id, v) VALUES (NULL, 1);
CREATE TABLE plain_rowid (id int) WITH ROWID;
INSERT INTO plain_rowid VALUES (1), (2);
CREATE INDEX user_rowid_idx ON plain_rowid (rowid);
CREATE TYPE other_t AS OBJECT (name varchar2(10));
/
CREATE TABLE others OF other_t;
INSERT INTO others VALUES (other_t('a')), (other_t('b'));
CREATE TABLE holder (p REF other_t);
INSERT INTO holder SELECT REF(o) FROM others o;
CREATE TYPE has_ref AS OBJECT (p REF other_t);
/
CREATE TABLE ref_holder (v has_ref);
INSERT INTO ref_holder SELECT has_ref(h.p) FROM holder h;
CREATE TABLE prt (id int, k int) PARTITION BY RANGE (k) WITH ROWID;
CREATE TABLE prt1 PARTITION OF prt FOR VALUES FROM (0) TO (10);
INSERT INTO prt VALUES (1, 1), (2, 2);
CREATE SEQUENCE coll_rowid_seq;
CREATE TABLE coll (id int) WITH ROWID;
INSERT INTO coll VALUES (1);
},
	connect_to_oraport => 1);

# PostgreSQL-style identity columns can live in the same cluster.
$old->safe_psql(
	'postgres', q{
CREATE TABLE pg_always (id int GENERATED ALWAYS AS IDENTITY, v int);
CREATE TABLE pg_default (id bigint GENERATED BY DEFAULT AS IDENTITY (CACHE 5), v int);
INSERT INTO pg_always (v) VALUES (1);
INSERT INTO pg_default (v) VALUES (1);
});

# The pg_type OIDs of the object type, its REF domain and their arrays must
# survive, since stored values can refer to them.
my $catalog_query = q{
SELECT n.nspname, p.pkgname, pg_catalog.pg_get_userbyid(p.pkgowner),
       p.pkgacl, md5(p.pkgsrc), md5(coalesce(b.bodysrc, '')),
       coalesce(obj_description(p.oid, 'pg_package'), '')
FROM pg_catalog.pg_package p
JOIN pg_catalog.pg_namespace n ON n.oid = p.pkgnamespace
LEFT JOIN pg_catalog.pg_package_body b ON b.pkgoid = p.oid
WHERE n.nspname NOT IN ('pg_catalog', 'sys')
ORDER BY 1, 2;
SELECT pkgname, pkgacl FROM pg_catalog.pg_package
WHERE pkgnamespace = 'sys'::regnamespace ORDER BY 1;
SELECT pg_catalog.pg_get_userbyid(d.defaclrole), n.nspname, d.defaclobjtype,
       d.defaclacl
FROM pg_catalog.pg_default_acl d
LEFT JOIN pg_catalog.pg_namespace n ON n.oid = d.defaclnamespace
ORDER BY 1, 2, 3;
SELECT a.attrelid::regclass, a.attname, a.atttypid::regtype, a.atttypmod
FROM pg_catalog.pg_attribute a
JOIN pg_catalog.pg_type t ON t.typrelid = a.attrelid
WHERE t.typisobject AND a.attnum > 0
ORDER BY a.attrelid::regclass::text, a.attnum;
SELECT a::text FROM attr_tab;
SELECT oid, typname, typarray, typrefbase FROM pg_catalog.pg_type
WHERE typname = 'obj_t' OR typrefbase <> 0 ORDER BY oid;
SELECT c.oid, c.relname, c.relpersistence, s.seqtypid::regtype, s.seqstart, s.seqincrement,
       s.seqmax, s.seqmin, s.seqcache, s.seqcycle, s.flags, q.last_value
FROM pg_catalog.pg_sequence s
JOIN pg_catalog.pg_class c ON c.oid = s.seqrelid
JOIN pg_catalog.pg_sequences q
  ON q.schemaname = 'public' AND q.sequencename = c.relname
ORDER BY c.relname;
SELECT a.attrelid::regclass, a.attname, a.atttypid::regtype, a.attidentity,
       a.attnotnull, pg_catalog.pg_get_serial_sequence(a.attrelid::regclass::text, a.attname)
FROM pg_catalog.pg_attribute a
JOIN pg_catalog.pg_class c ON c.oid = a.attrelid
WHERE c.relnamespace = 'public'::regnamespace AND c.relkind = 'r'
  AND a.attnum > 0 AND NOT a.attisdropped
ORDER BY 1, 2;
SELECT 'plain_rowid', rowid::text, id FROM plain_rowid ORDER BY 3;
SELECT 'others', o.rowid::text, o.name FROM others o ORDER BY 3;
SELECT 'holder', h.p::text FROM holder h ORDER BY 2;
SELECT 'ref_holder', x.v::text FROM ref_holder x ORDER BY 2;
SELECT 'prt', rowid::text, id FROM prt ORDER BY 3;
SELECT 'coll', rowid::text, id FROM coll ORDER BY 3;
SELECT c.oid, c.relname, c.relkind, c.relfilenode, c.relhasrowid
FROM pg_catalog.pg_class c
WHERE c.relnamespace = 'public'::regnamespace
  AND (c.relhasrowid OR c.relname LIKE '%rowid%')
ORDER BY 1;
SELECT d.objid::regclass::text, d.refobjid::regclass::text, d.refobjsubid
FROM pg_catalog.pg_depend d
JOIN pg_catalog.pg_class s ON s.oid = d.objid
WHERE d.classid = 'pg_catalog.pg_class'::regclass AND s.relhasrowid
  AND s.relkind = 'S' AND d.deptype = 'a'
ORDER BY 1;
SELECT 'rowid seq', last_value, is_called FROM plain_rowid_rowid_seq
UNION ALL SELECT 'rowid seq', last_value, is_called FROM others_rowid_seq
UNION ALL SELECT 'rowid seq', last_value, is_called FROM prt_rowid_seq
UNION ALL SELECT 'rowid seq', last_value, is_called FROM prt1_rowid_seq
UNION ALL SELECT 'rowid seq', last_value, is_called FROM coll_rowid_seq
UNION ALL SELECT 'rowid seq', last_value, is_called FROM coll_rowid_seq1;
SELECT 'ora_always', * FROM ora_always
UNION ALL SELECT 'ora_default', * FROM ora_default
UNION ALL SELECT 'ora_on_null', * FROM ora_on_null
UNION ALL SELECT 'pg_always', * FROM pg_always
UNION ALL SELECT 'pg_default', * FROM pg_default
ORDER BY 1, 2;
};
my $usage_query = q{
DECLARE
  o obj_t;
BEGIN
  FOR r IN (SELECT t.o FROM obj_tab t) LOOP
    o := r.o;
  END LOOP;
  RAISE NOTICE '% % % %', "MixSch"."MixPkg".hello(), spec_only.answer,
    o.doubled(), o.tripled();
END;
};
my $expected_catalog = $old->safe_psql('postgres', $catalog_query);
$old->stop;

# pg_upgrade writes files into its working directory.
chdir ${PostgreSQL::Test::Utils::tmp_check};

sub upgrade_ok
{
	my ($new, @extra) = @_;

	command_ok(
		[
			'pg_upgrade', '--no-sync', '--copy',
			'--old-datadir' => $old->data_dir,
			'--new-datadir' => $new->data_dir,
			'--old-bindir' => $old->config_data('--bindir'),
			'--new-bindir' => $new->config_data('--bindir'),
			'--socketdir' => $new->host,
			'--old-port' => $old->port,
			'--new-port' => $new->port,
			'--old-oraport' => $old->oraport,
			'--new-oraport' => $new->oraport,
			@extra
		],
		"pg_upgrade @extra");
}

for my $extra ([], ['--using-ora-pg'])
{
	my $label = @$extra ? 'upgrade through the PostgreSQL port'
	  : 'upgrade through the Oracle port';
	my $new = PostgreSQL::Test::Cluster->new(
		@$extra ? 'new_using_ora_pg' : 'new_default');
	$new->init;

	upgrade_ok($new, @$extra);
	$new->start;

	is($new->safe_psql('postgres', $catalog_query),
		$expected_catalog,
		"$label preserves packages, object types, sequences and identity columns");

	my $notice;
	$new->psql(
		'postgres', $usage_query,
		stderr => \$notice,
		on_error_die => 1,
		connect_to_oraport => 1);
	like($notice, qr/hello from MixPkg 42 42 63/,
		"$label keeps packages and stored object values usable");

	# Each identity keeps its kind: ALWAYS refuses a value, ON NULL fills one.
	is( $new->safe_psql(
			'postgres', q{
INSERT INTO ora_always (v) VALUES (3);
INSERT INTO ora_on_null (id, v) VALUES (NULL, 2);
SELECT count(DISTINCT id) FROM ora_always;
SELECT count(*) FROM ora_on_null WHERE id IS NOT NULL;
},
			connect_to_oraport => 1),
		"3\n2",
		"$label keeps identity columns generating values");
	is( $new->safe_psql(
			'postgres', q{
INSERT INTO plain_rowid VALUES (3);
INSERT INTO others VALUES (other_t('c'));
INSERT INTO prt VALUES (3, 3);
SELECT count(DISTINCT rowid) FROM plain_rowid;
SELECT count(DISTINCT o.rowid) FROM others o;
SELECT count(DISTINCT rowid) FROM prt;
SELECT string_agg((DEREF(h.p)).name::text, ',' ORDER BY h.p::text) FROM holder h;
SELECT string_agg((DEREF((x.v).p)).name::text, ',' ORDER BY (x.v).p::text)
FROM ref_holder x;
},
			connect_to_oraport => 1),
		"3\n3\n3\n(a),(b)\n(a),(b)",
		"$label keeps ROWIDs unique for new rows and REFs pointing at their rows");
	my ($ret, $stdout, $stderr) = $new->psql('postgres',
		'INSERT INTO ora_always (id, v) VALUES (99, 4)',
		connect_to_oraport => 1);
	is($ret, 3, "$label fails an explicit value for an ALWAYS identity");
	like($stderr,
		qr/cannot insert a generated always identity column "id"/,
		"$label keeps an ALWAYS identity refusing explicit values");

	$new->stop;
}

# A PostgreSQL-mode cluster is dumped in PostgreSQL syntax and is restored
# through the PostgreSQL port of an Oracle-mode cluster, without
# --using-ora-pg.  A sequence with a cache of 1 has no Oracle-mode spelling.
my $pg_src = PostgreSQL::Test::Cluster->new('pg_mode_source');
$pg_src->init(extra => [ '-m', 'pg' ]);
$pg_src->start;
$pg_src->safe_psql(
	'postgres', q{
CREATE SEQUENCE pg_seq;
CREATE TABLE pg_ident (id int GENERATED ALWAYS AS IDENTITY, v int);
INSERT INTO pg_ident (v) VALUES (1);
});
my $pg_query = q{
SELECT c.relname, s.seqtypid::regtype, s.seqstart, s.seqincrement, s.seqmax,
       s.seqmin, s.seqcache, s.seqcycle
FROM pg_catalog.pg_sequence s
JOIN pg_catalog.pg_class c ON c.oid = s.seqrelid
WHERE c.relnamespace = 'public'::regnamespace
ORDER BY 1;
SELECT attidentity FROM pg_catalog.pg_attribute
WHERE attrelid = 'pg_ident'::regclass AND attname = 'id';
SELECT * FROM pg_ident;
};
my $pg_expected = $pg_src->safe_psql('postgres', $pg_query);
$pg_src->stop;

my $ora_dst = PostgreSQL::Test::Cluster->new('oracle_mode_target');
$ora_dst->init;
command_ok(
	[
		'pg_upgrade', '--no-sync', '--copy',
		'--old-datadir' => $pg_src->data_dir,
		'--new-datadir' => $ora_dst->data_dir,
		'--old-bindir' => $pg_src->config_data('--bindir'),
		'--new-bindir' => $ora_dst->config_data('--bindir'),
		'--socketdir' => $ora_dst->host,
		'--old-port' => $pg_src->port,
		'--new-port' => $ora_dst->port,
		'--new-oraport' => $ora_dst->oraport
	],
	'pg_upgrade of a PostgreSQL-mode cluster into an Oracle-mode one');
$ora_dst->start;
is($ora_dst->safe_psql('postgres', $pg_query),
	$pg_expected,
	'upgrade into Oracle mode keeps sequences and identity columns');
is($ora_dst->safe_psql('postgres',
		'INSERT INTO pg_ident (v) VALUES (2) RETURNING id'),
	'2', 'upgrade into Oracle mode keeps the identity generating values');
$ora_dst->stop;

# An Oracle-mode cluster cannot move into a PostgreSQL-mode one.
my $pg_mode = PostgreSQL::Test::Cluster->new('new_pg_mode');
$pg_mode->init(extra => [ '-m', 'pg' ]);
# pg_upgrade reports check failures on stdout.
command_checks_all(
	[
		'pg_upgrade', '--no-sync', '--check',
		'--old-datadir' => $old->data_dir,
		'--new-datadir' => $pg_mode->data_dir,
		'--old-bindir' => $old->config_data('--bindir'),
		'--new-bindir' => $pg_mode->config_data('--bindir'),
		'--socketdir' => $pg_mode->host,
		'--old-port' => $old->port,
		'--new-port' => $pg_mode->port,
		'--using-ora-pg'
	],
	1,
	[qr/old cluster was initialized in Oracle mode but the new one was not/],
	[],
	'pg_upgrade refuses an Oracle-mode cluster into a PostgreSQL-mode one');

done_testing();
