-- The three *_CONS_COLUMNS views must describe the same constraints: one row
-- per constraint column, one name, no system columns, and no extra NOT NULL row
-- for a column a primary key already covers.
CREATE TABLE t_cons_agree (
    id INT PRIMARY KEY,
    name VARCHAR2(10) NOT NULL,
    note VARCHAR2(10)
);
SELECT (SELECT COUNT(*) FROM SYS.USER_CONS_COLUMNS
        WHERE TABLE_NAME = 'T_CONS_AGREE') = (
       SELECT COUNT(*) FROM SYS.ALL_CONS_COLUMNS
        WHERE TABLE_NAME = 'T_CONS_AGREE'
          AND OWNER = SYS.ORA_CASE_TRANS(CURRENT_USER::VARCHAR2)) AS user_matches_all;

SELECT (SELECT COUNT(*) FROM SYS.DBA_CONS_COLUMNS
        WHERE TABLE_NAME = 'T_CONS_AGREE') = (
       SELECT COUNT(*) FROM SYS.ALL_CONS_COLUMNS
        WHERE TABLE_NAME = 'T_CONS_AGREE') AS dba_matches_all;

SELECT COUNT(*) = 0 AS no_system_columns
FROM SYS.DBA_CONS_COLUMNS
WHERE TABLE_NAME = 'T_CONS_AGREE'
  AND COLUMN_NAME IN ('CTID', 'CMIN', 'CMAX', 'XMIN', 'XMAX', 'TABLEOID');

SELECT COUNT(*) = 0 AS no_duplicate_rows
FROM (
    SELECT TABLE_NAME, COLUMN_NAME, POSITION
    FROM SYS.DBA_CONS_COLUMNS
    WHERE TABLE_NAME = 'T_CONS_AGREE'
    GROUP BY TABLE_NAME, COLUMN_NAME, POSITION
    HAVING COUNT(*) > 1
) D;

SELECT CONSTRAINT_NAME, COLUMN_NAME, POSITION
FROM SYS.USER_CONS_COLUMNS
WHERE TABLE_NAME = 'T_CONS_AGREE'
ORDER BY CONSTRAINT_NAME, COLUMN_NAME;

DROP TABLE t_cons_agree;

-- ALL_TAB_COLUMNS must name every Oracle type the way Oracle does; the
-- character-semantics variants and the zoned timestamps used to leak the
-- internal type name (ORAVARCHARCHAR, ORATIMESTAMPLTZ) or lose the qualifier
CREATE TABLE t_all_data_types (
    a VARCHAR2(10 CHAR),
    b CHAR(5 CHAR),
    c TIMESTAMP WITH TIME ZONE,
    d TIMESTAMP WITH LOCAL TIME ZONE,
    e LONG RAW,
    f BOOLEAN,
    g NCLOB
);
SELECT COUNT(*) = 7 AS all_types_listed
FROM SYS.ALL_TAB_COLUMNS
WHERE TABLE_NAME = 'T_ALL_DATA_TYPES';

SELECT COUNT(*) = 7 AS data_types_match
FROM SYS.ALL_TAB_COLUMNS
WHERE TABLE_NAME = 'T_ALL_DATA_TYPES'
  AND (   (COLUMN_NAME = 'A' AND DATA_TYPE = 'VARCHAR2' AND CHAR_USED = 'C')
       OR (COLUMN_NAME = 'B' AND DATA_TYPE = 'CHAR' AND CHAR_USED = 'C')
       OR (COLUMN_NAME = 'C' AND DATA_TYPE = 'TIMESTAMP WITH TIME ZONE')
       OR (COLUMN_NAME = 'D' AND DATA_TYPE = 'TIMESTAMP WITH LOCAL TIME ZONE')
       OR (COLUMN_NAME = 'E' AND DATA_TYPE = 'LONG RAW')
       OR (COLUMN_NAME = 'F' AND DATA_TYPE = 'BOOLEAN')
       OR (COLUMN_NAME = 'G' AND DATA_TYPE = 'NCLOB'));
DROP TABLE t_all_data_types;

-- Timestamp columns report their fractional-seconds precision in DATA_SCALE,
-- and NCLOB reports the same DATA_LENGTH as CLOB and BLOB
CREATE TABLE t_ts_meta (
    a TIMESTAMP,
    b TIMESTAMP(3),
    c TIMESTAMP(0),
    d TIMESTAMP(3) WITH TIME ZONE,
    e NCLOB
);
SELECT COUNT(*) = 5 AS five_columns
FROM SYS.ALL_TAB_COLUMNS
WHERE TABLE_NAME = 'T_TS_META';

SELECT COUNT(*) = 5 AS meta_matches
FROM SYS.ALL_TAB_COLUMNS
WHERE TABLE_NAME = 'T_TS_META'
  AND (   (COLUMN_NAME = 'A' AND DATA_SCALE = 6 AND DATA_LENGTH = 11)
       OR (COLUMN_NAME = 'B' AND DATA_SCALE = 3 AND DATA_LENGTH = 11)
       OR (COLUMN_NAME = 'C' AND DATA_SCALE = 0 AND DATA_LENGTH = 7)
       OR (COLUMN_NAME = 'D' AND DATA_SCALE = 3 AND DATA_LENGTH = 13)
       OR (COLUMN_NAME = 'E' AND DATA_LENGTH = 4000 AND DATA_SCALE IS NULL));
DROP TABLE t_ts_meta;

