/* Parse a package spec's routine signatures into argument rows.
 * Used by DBA/ALL/USER_ARGUMENTS: packaged routines have no pg_proc
 * entries, their signatures only live in pg_package.pkgsrc.
 * FUNCTION|PROCEDURE name [(arg [IN|OUT|IN OUT] type, ...)] [RETURN type];
 * Overloaded declarations get distinct OVERLOAD_IDX values.
 * NB: never compare against '' here - Oracle-mode sessions treat the
 * empty string as NULL.
 */
CREATE OR REPLACE FUNCTION SYS._ORA_PKG_ARGUMENTS(PKGOID OID)
RETURNS TABLE(
	OWNER NAME,
	PACKAGE_NAME NAME,
	OBJECT_NAME TEXT,
	IS_FUNCTION BOOLEAN,
	ARGUMENT_NAME TEXT,
	ARG_POSITION INT,
	IN_OUT TEXT,
	ARG_TYPE TEXT,
	OVERLOAD_IDX INT
) AS $$
DECLARE
	SRC TEXT;
	TAIL TEXT;
	HEAD_M TEXT[];
	SEEN TEXT[];
	KIND TEXT;
	NAM TEXT;
	ARGSTR TEXT;
	RETSTR TEXT;
	ONEARG TEXT;
	W TEXT;
	ARGNAM TEXT;
	MODE VARCHAR2(10);
	REST TEXT;
	TOK TEXT;
	POS INT;
	ARGPOS INT;
	DEPTH INT;
	I INT;
BEGIN
	SELECT PKGSRC INTO SRC FROM PG_CATALOG.PG_PACKAGE WHERE OID = PKGOID;
	IF SRC IS NULL OR LENGTH(TRIM(SRC)) = 0 THEN
		RETURN;
	END IF;

	/* strip comments and collapse whitespace so the spec parses linearly */
	TAIL := REGEXP_REPLACE(SRC, '/\*.*?\*/', ' ', 'g');
	TAIL := REGEXP_REPLACE(TAIL, '--[^\n]*', ' ', 'g');
	TAIL := REGEXP_REPLACE(TAIL, '[[:space:]]+', ' ', 'g');

	SELECT PG_GET_USERBYID(PKGOWNER), PKGNAME
		INTO OWNER, PACKAGE_NAME
		FROM PG_CATALOG.PG_PACKAGE WHERE OID = PKGOID;

	SEEN := ARRAY[]::TEXT[];
	LOOP
		TAIL := LTRIM(TAIL);
		EXIT WHEN TAIL IS NULL OR LENGTH(TAIL) = 0;
		HEAD_M := REGEXP_MATCH(TAIL, '(?i)^(FUNCTION|PROCEDURE) ([A-Za-z_][A-Za-z0-9_$#]*)');
		EXIT WHEN HEAD_M IS NULL;
		KIND := UPPER(HEAD_M[1]);
		NAM := HEAD_M[2];
		SEEN := SEEN || (KIND || ' ' || UPPER(NAM));
		OVERLOAD_IDX := CARDINALITY(ARRAY_POSITIONS(SEEN, KIND || ' ' || UPPER(NAM)));
		TAIL := SUBSTR(TAIL, LENGTH(HEAD_M[1]) + LENGTH(HEAD_M[2]) + 2);

		/* optional parenthesized argument list (nesting-aware) */
		ARGSTR := NULL;
		IF SUBSTRING(LTRIM(TAIL) FROM 1 FOR 1) = '(' THEN
			TAIL := LTRIM(TAIL);
			DEPTH := 0;
			I := 0;
			LOOP
				I := I + 1;
				EXIT WHEN I > LENGTH(TAIL);
				IF SUBSTRING(TAIL FROM I FOR 1) = '(' THEN
					DEPTH := DEPTH + 1;
				ELSIF SUBSTRING(TAIL FROM I FOR 1) = ')' THEN
					DEPTH := DEPTH - 1;
					IF DEPTH = 0 THEN
						ARGSTR := TRIM(SUBSTRING(TAIL FROM 2 FOR I - 2));
						TAIL := SUBSTRING(TAIL FROM I + 1);
						EXIT;
					END IF;
				END IF;
			END LOOP;
		END IF;

		/* optional RETURN type up to the terminating semicolon */
		RETSTR := NULL;
		POS := POSITION(';' IN TAIL);
		IF POS > 0 THEN
			REST := TRIM(SUBSTRING(TAIL FROM 1 FOR POS - 1));
			TAIL := SUBSTRING(TAIL FROM POS + 1);
			IF KIND = 'FUNCTION' THEN
				RETSTR := SUBSTRING(REST FROM '(?i)^RETURN +(.+)$');
			END IF;
		ELSE
			TAIL := '';
		END IF;

		IF KIND = 'FUNCTION' AND RETSTR IS NOT NULL THEN
			OBJECT_NAME := NAM;
			IS_FUNCTION := TRUE;
			ARGUMENT_NAME := NULL;
			ARG_POSITION := 0;
			IN_OUT := 'OUT';
			ARG_TYPE := RETSTR;
			RETURN NEXT;
		END IF;

		IF ARGSTR IS NOT NULL AND LENGTH(ARGSTR) > 0 THEN
			/* split the argument list on top-level commas */
			DEPTH := 0;
			W := '';
			ARGPOS := 0;
			FOR I IN 1 .. LENGTH(ARGSTR) + 1 LOOP
				ONEARG := NULL;		/* NULL marks a split point */
				IF I <= LENGTH(ARGSTR) THEN
					ONEARG := SUBSTRING(ARGSTR FROM I FOR 1);
					IF ONEARG = '(' THEN
						DEPTH := DEPTH + 1;
					ELSIF ONEARG = ')' THEN
						DEPTH := DEPTH - 1;
					END IF;
					IF ONEARG = ',' AND DEPTH = 0 THEN
						ONEARG := NULL;
					ELSE
						W := W || ONEARG;
					END IF;
				END IF;
				IF ONEARG IS NULL THEN
					ONEARG := TRIM(W);
					W := '';
					IF ONEARG IS NOT NULL AND LENGTH(ONEARG) > 0 THEN
						ARGPOS := ARGPOS + 1;
						/* name, then optional mode keywords, rest is the type */
						ARGNAM := SUBSTRING(ONEARG FROM '^([A-Za-z_][A-Za-z0-9_$#]*)');
						REST := TRIM(SUBSTRING(ONEARG FROM LENGTH(ARGNAM) + 1));
						MODE := 'IN';
						LOOP
							IF REST ~* '^IN +OUT\y' THEN
								MODE := 'IN/OUT';
								REST := TRIM(SUBSTRING(REST FROM 7));
							ELSIF REST ~* '^(IN|OUT|INOUT|NOCOPY)\y' THEN
								TOK := UPPER(SUBSTRING(REST FROM '^([A-Za-z]+)'));
								IF TOK <> 'NOCOPY' THEN
									MODE := CASE TOK WHEN 'IN' THEN 'IN'
													WHEN 'OUT' THEN 'OUT'
													ELSE 'IN/OUT' END;
								END IF;
								REST := TRIM(SUBSTRING(REST FROM LENGTH(TOK) + 2));
							ELSE
								EXIT;
							END IF;
						END LOOP;
						/* a spec argument type ends at a DEFAULT or := clause */
						ARG_TYPE := TRIM(SYS.REGEXP_REPLACE(REST, '(?i) +(DEFAULT|:=) .*$', ''));
						OBJECT_NAME := NAM;
						IS_FUNCTION := (KIND = 'FUNCTION');
						ARGUMENT_NAME := ARGNAM;
						ARG_POSITION := ARGPOS;
						IN_OUT := MODE;
						RETURN NEXT;
					END IF;
				END IF;
			END LOOP;
		END IF;
	END LOOP;
END;
