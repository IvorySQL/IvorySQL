-- V$SESSION:
-- 1. For SID we use PG_STAT_ACTIVITY.PID and do not set SERIAL#:
-- we should avoid implementing "killing by SID" without either an additional counter or second factor like PG_STAT_ACTIVITY.BACKEND_START.
-- 2. SQL_ID is based on PG_STAT_ACTIVITY.QUERY_ID which depends on compute_query_id setting: SQL_ID is NULL if compute_query_id is 'off'.
-- SQL_ID is incompatible with Oracle because QUERY_ID a integer string in PostgreSQL and in Oracle SQL_ID is 13-character base32-encoded
-- hash.
-- 
-- We do not grant SELECT privilege on V$SESSION to PUBLIC because SQL_TEXT is retrieved.
-- We do not grant SELECT privilege on V$PROCESS or on V$PARAMETER to PUBLIC
-- because it contradicts with least security privilege principle.

CREATE OR REPLACE VIEW SYS.V$SESSION AS
SELECT
    PG_STAT_ACTIVITY.PID::NUMBER AS SID,
    USENAME::VARCHAR2(128) AS USERNAME,
    CASE WHEN STATE = 'active' OR STATE = 'fastpath function call' THEN 'ACTIVE'
         WHEN STATE = 'idle' OR STATE = 'idle in transaction'
               OR STATE = 'idle in transaction (aborted)' THEN 'INACTIVE'
         ELSE 'INACTIVE' 
         END::VARCHAR2(40) AS STATUS,
    COALESCE(CLIENT_HOSTNAME, HOST(CLIENT_ADDR),CLIENT_ADDR::TEXT)::VARCHAR2(128) AS MACHINE,
    APPLICATION_NAME::VARCHAR2(256) AS PROGRAM,
    CASE WHEN BACKEND_TYPE = 'client backend' THEN 'USER'
    ELSE 'BACKGROUND'
    END::VARCHAR2(30) AS TYPE,
    BACKEND_START AS LOGON_TIME,
    QUERY_START AS SQL_EXEC_START,
    QUERY_ID::VARCHAR2(19) AS SQL_ID,
    QUERY::VARCHAR2(4000) AS SQL_TEXT,
    (PG_CATALOG.PG_BLOCKING_PIDS(PID))[1]::NUMBER AS BLOCKING_SESSION,
    WAIT_EVENT::VARCHAR2(64) AS EVENT,
    WAIT_EVENT_TYPE::VARCHAR2(64) AS WAIT_CLASS,
    XACT_START AS TRANSACTION_START,
    CLIENT_PORT::NUMBER AS PORT,
    USESYSID::INT8::NUMBER AS "USER#",
    PID::VARCHAR2(20) AS PROCESS,
    CASE WHEN NOW() < COALESCE(STATE_CHANGE, BACKEND_START) THEN 0
         ELSE EXTRACT(EPOCH FROM (NOW() - COALESCE(STATE_CHANGE, BACKEND_START)))::NUMBER
    END AS LAST_CALL_ET
FROM PG_STAT_ACTIVITY;


-- V$PROCESS: USERNAME maps to the database username (pg_stat_activity.usename),
-- not the OS username as in Oracle V$PROCESS.
CREATE OR REPLACE VIEW SYS.V$PROCESS AS
SELECT
    PID::NUMBER AS SPID,
    USENAME::VARCHAR2(128) AS USERNAME,
    APPLICATION_NAME::VARCHAR2(256) AS PROGRAM,
    BACKEND_TYPE::VARCHAR2(30) AS PNAME,
    CASE WHEN BACKEND_TYPE =  'client backend' THEN NULL
         ELSE '1'
    END::VARCHAR2(1) AS BACKGROUND,
    PID::NUMBER AS PID
FROM PG_STAT_ACTIVITY;

-- V$PARAMETER: the documented Oracle column list, in Oracle's order.
-- NUM/ORDINAL are the parameter's position in name order, DISPLAY_VALUE
-- renders booleans the way Oracle prints them, and ISPDB_MODIFIABLE,
-- ISADJUSTED, ISBASIC, UPDATE_COMMENT and HASH have no PostgreSQL
-- counterpart: there are no per-PDB parameters, the server never adjusts a
-- value behind the user's back, and PostgreSQL neither classifies "basic"
-- parameters nor exposes a parameter hash.
CREATE OR REPLACE VIEW SYS.V$PARAMETER AS
SELECT
    ROW_NUMBER() OVER (ORDER BY NAME)::NUMBER AS NUM,
    NAME::VARCHAR2(80) AS NAME,
    CASE
        WHEN VARTYPE = 'bool'    THEN 1
        WHEN VARTYPE = 'integer' THEN 3
        ELSE 2
    END::NUMBER AS TYPE,
    SETTING::VARCHAR2(4000) AS VALUE,
    CASE
        WHEN VARTYPE = 'bool' THEN
            CASE WHEN SETTING = 'on' THEN 'TRUE' ELSE 'FALSE' END
        ELSE
            SETTING
    END::VARCHAR2(4000) AS DISPLAY_VALUE,
    BOOT_VAL::VARCHAR2(255) AS DEFAULT_VALUE,
    -- Mapping update levels
    CASE
        WHEN setting IS NOT DISTINCT FROM boot_val THEN 'TRUE'
        ELSE 'FALSE'
    END::VARCHAR2(5) AS ISDEFAULT,
    CASE
        WHEN CONTEXT IN ('user', 'superuser') THEN 'TRUE'
        ELSE 'FALSE'
    END::VARCHAR2(5) AS ISSES_MODIFIABLE,
    CASE
        WHEN CONTEXT IN ('user', 'superuser','sighup') THEN 'IMMEDIATE'
        WHEN CONTEXT IN ('postmaster','internal') THEN 'FALSE'
        ELSE 'DEFERRED'
    END::VARCHAR2(9) AS ISSYS_MODIFIABLE,
    'FALSE'::VARCHAR2(5) AS ISPDB_MODIFIABLE,
    ROW_NUMBER() OVER (ORDER BY NAME)::NUMBER AS ORDINAL,
    'FALSE'::VARCHAR2(5) AS ISADJUSTED,
    'FALSE'::VARCHAR2(5) AS ISBASIC,
    SHORT_DESC::VARCHAR2(255) AS DESCRIPTION,
    NULL::VARCHAR2(255) AS UPDATE_COMMENT,
    NULL::NUMBER AS HASH
FROM PG_SETTINGS;

CREATE OR REPLACE VIEW SYS.all_cons_columns AS
SELECT
    SYS.ORA_CASE_TRANS(pg_authid.rolname::VARCHAR2(128))    AS owner,
    SYS.ORA_CASE_TRANS(con.conname::VARCHAR2(128))          AS constraint_name,
    SYS.ORA_CASE_TRANS(cls.relname::VARCHAR2(128))          AS table_name,
    SYS.ORA_CASE_TRANS(attr.attname::VARCHAR2(4000))        AS column_name,
    pos.pos::NUMBER                                         AS position
FROM
    pg_catalog.pg_constraint con
    JOIN pg_catalog.pg_class cls       ON con.conrelid = cls.oid
    JOIN pg_catalog.pg_authid          ON cls.relowner = pg_authid.oid
    JOIN pg_catalog.pg_namespace nsp   ON cls.relnamespace = nsp.oid
    CROSS JOIN LATERAL unnest(con.conkey) WITH ORDINALITY AS pos(attnum, pos)
    JOIN pg_catalog.pg_attribute attr  ON attr.attrelid = cls.oid
                                      AND attr.attnum = pos.attnum
WHERE
    con.contype IN ('p', 'u', 'f', 'c')
    AND nsp.nspname NOT IN ('pg_catalog', 'information_schema', 'pg_toast')
    AND cls.relkind IN ('r', 'v', 'm', 'p')
    AND attr.attnum > 0
    AND NOT attr.attisdropped
    AND has_schema_privilege(nsp.oid, 'USAGE')
    AND has_table_privilege(cls.oid, 'SELECT')

UNION ALL
SELECT
    SYS.ORA_CASE_TRANS(pg_authid.rolname::VARCHAR2(128))    AS owner,
    SYS.ORA_CASE_TRANS((cls.relname || '_' || attr.attname || '_NOT_NULL')::VARCHAR2(128)) AS constraint_name,
    SYS.ORA_CASE_TRANS(cls.relname::VARCHAR2(128))          AS table_name,
    SYS.ORA_CASE_TRANS(attr.attname::VARCHAR2(4000))        AS column_name,
    1::NUMBER                                              AS position
FROM
    pg_catalog.pg_class cls
    JOIN pg_catalog.pg_authid          ON cls.relowner = pg_authid.oid
    JOIN pg_catalog.pg_namespace nsp   ON cls.relnamespace = nsp.oid
    JOIN pg_catalog.pg_attribute attr  ON attr.attrelid = cls.oid
WHERE
    attr.attnotnull                    
    AND attr.attnum > 0
    AND NOT attr.attisdropped
    AND nsp.nspname NOT IN ('pg_catalog', 'information_schema', 'pg_toast')
    AND cls.relkind IN ('r', 'v', 'm', 'p')
    AND has_schema_privilege(nsp.oid, 'USAGE')
    AND has_table_privilege(cls.oid, 'SELECT')
    AND NOT EXISTS (
        SELECT 1 FROM pg_catalog.pg_constraint con
        WHERE con.conrelid = cls.oid
          AND con.contype = 'p'
          AND con.conkey && ARRAY[attr.attnum]
    )
ORDER BY
    owner, table_name, constraint_name, position;
GRANT SELECT ON SYS.all_cons_columns TO PUBLIC;
