/* ARGUMENTS' TYPE COUNT */
CREATE OR REPLACE FUNCTION SYS._ORA_ARGS_COUNT(PROID OID)
RETURNS INTEGER
AS $$
DECLARE
	RET INTEGER;
BEGIN
	SELECT
		COUNT(1)
	FROM
	(
		SELECT
			UNNEST(
				CASE
					WHEN PROALLARGTYPES IS NOT NULL
						THEN PROALLARGTYPES
					ELSE PROARGTYPES
				END
			)
		FROM
			PG_PROC
		WHERE OID = $1
	) AS SQ
	INTO
		RET;
	RETURN RET;
END;
$$ LANGUAGE PLPGSQL IMMUTABLE;

/* Shared argument rows for the three Oracle dictionary views. */
CREATE OR REPLACE VIEW SYS._ORA_ARGUMENTS AS
WITH PACKAGE_ROUTINES AS
(
    SELECT S.*,
           COUNT(*) OVER (PARTITION BY S.OID, S.PROC_NAME) AS OVERLOAD_COUNT,
           ROW_NUMBER() OVER (PARTITION BY S.OID, S.PROC_NAME ORDER BY S.FNO) AS OVERLOAD_NO
    FROM PG_CATALOG.PG_GET_SUBPROCS_IN_PACKAGE() S
),
ARGUMENT_ROWS AS
(
    SELECT P.PROOWNER AS OWNER_OID, P.PRONAMESPACE AS NAMESPACE_OID,
           P.OID AS OBJECT_OID, P.PRONAME::TEXT AS OBJECT_NAME,
           NULL::TEXT AS PACKAGE_NAME, NULL::TEXT AS OVERLOAD,
           1 AS SUBPROGRAM_ID, P.PROKIND AS KIND,
           SQ.ARGUMENT_NAME, SQ.DATA_TYPE, SQ.IN_OUT, SQ.POSITION,
           PG_CATALOG.PG_GET_FUNCTION_ARG_DEFAULT(P.OID, SQ.POSITION) IS NOT NULL AS DEFAULTED,
           ARG.TYPE_NAME, ARG.TYPE_SUBNAME, ARG.TYPE_OBJECT_TYPE,
           ARG.DATA_LENGTH, ARG.DATA_PRECISION, ARG.DATA_SCALE, ARG.PLS_TYPE
    FROM PG_CATALOG.PG_PROC P
    CROSS JOIN LATERAL
    (
        -- A function return is a real row, including for a no-argument function.
        SELECT NULL::TEXT AS ARGUMENT_NAME, P.PRORETTYPE AS DATA_TYPE,
               'o'::TEXT AS IN_OUT, 0 AS POSITION
        WHERE P.PROKIND = 'f'
        UNION ALL
        -- WITH ORDINALITY works for both zero-based oidvectors and oid arrays.
        SELECT P.PROARGNAMES[X.ORD], X.TYPE_OID,
               COALESCE(P.PROARGMODES[X.ORD]::TEXT, 'i'::TEXT), X.ORD::INTEGER
        FROM UNNEST(COALESCE(P.PROALLARGTYPES, P.PROARGTYPES::OID[]))
             WITH ORDINALITY AS X(TYPE_OID, ORD)
    ) SQ
    LEFT JOIN PG_CATALOG.PG_GET_FUNCTION_ARG_REFERENCE_TYPEROWTYPE() ARG
      ON ARG.OID = P.OID AND ARG.POSITION = SQ.POSITION
    WHERE P.PROKIND IN ('f', 'p')
      AND P.PRONAMESPACE NOT IN ('pg_catalog'::REGNAMESPACE,
                                'pg_toast'::REGNAMESPACE,
                                'information_schema'::REGNAMESPACE)
      AND NOT EXISTS (SELECT 1 FROM PG_CATALOG.PG_TRIGGER TR WHERE TR.TGFOID = P.OID)
    UNION ALL
    SELECT P.OWNER, P.NAMESPACE, P.OID, P.PROC_NAME, P.PACKAGE_NAME,
           CASE WHEN P.OVERLOAD_COUNT > 1 THEN P.OVERLOAD_NO::TEXT ELSE NULL END,
           P.FNO + 1, P.KIND,
           NULLIF(P.ARGNAMES[X.ORD], '_NULL_'), P.ARGTYPES[X.ORD - 1], P.ARGMODES[X.ORD]::TEXT,
           X.ORD - CASE WHEN P.KIND = 'f' THEN 1 ELSE 0 END,
           P.ARGDEFAULTS[X.ORD] IS NOT NULL AND P.ARGDEFAULTS[X.ORD] <> '_NULL_',
           P.TYPE_NAMES[X.ORD], NULL::TEXT, P.TYPE_OBJECT_TYPES[X.ORD],
           NULLIF(P.DATA_LENGTHS[X.ORD], 0),
           NULLIF(P.DATA_PRECISIONS[X.ORD], 0),
           CASE WHEN P.DATA_PRECISIONS[X.ORD] > 0 THEN P.DATA_SCALES[X.ORD] ELSE NULL END,
           P.ARGTYPENAMES[X.ORD]
    FROM PACKAGE_ROUTINES P
    CROSS JOIN LATERAL GENERATE_SUBSCRIPTS(P.ARGNAMES, 1) AS X(ORD)
)
SELECT
	SYS.ORA_CASE_TRANS(
		PG_GET_USERBYID(A.OWNER_OID)::VARCHAR2
	)::VARCHAR2(128) AS OWNER,
	SYS.ORA_CASE_TRANS(A.OBJECT_NAME::VARCHAR2)::VARCHAR2(128) AS OBJECT_NAME,
	SYS.ORA_CASE_TRANS(A.PACKAGE_NAME::VARCHAR2)::VARCHAR2(128) AS PACKAGE_NAME,
	A.OBJECT_OID::VARCHAR2(10)::NUMBER AS OBJECT_ID,
	A.OVERLOAD::VARCHAR2(40) AS OVERLOAD,
	A.SUBPROGRAM_ID::NUMBER AS SUBPROGRAM_ID,
	SYS.ORA_CASE_TRANS(
		A.ARGUMENT_NAME::VARCHAR2
	)::VARCHAR2(128) AS ARGUMENT_NAME,
	A.POSITION::NUMBER AS POSITION,
	CASE
		WHEN A.KIND = 'f'
			THEN A.POSITION + 1
		ELSE A.POSITION
	END::NUMBER AS SEQUENCE,
	0::NUMBER AS DATA_LEVEL,
	CASE
		WHEN A.TYPE_OBJECT_TYPE::VARCHAR2 = 'table' OR A.TYPE_OBJECT_TYPE::VARCHAR2 = 'TABLE'
		  OR A.TYPE_OBJECT_TYPE::VARCHAR2 = 'view' OR A.TYPE_OBJECT_TYPE::VARCHAR2 = 'VIEW'
		  THEN 'PL/SQL RECORD'
		WHEN T.TYPNAME = ANY(ARRAY['int2', 'int4', 'int8',
								   'numeric', 'number'])
			THEN 'NUMBER'
		WHEN T.TYPNAME = ANY(ARRAY['float4', 'float8'])
			THEN 'FLOAT'
		WHEN T.TYPNAME = 'bpchar'
			THEN 'CHAR'
		ELSE ORA_CASE_TRANS(T.OID::REGTYPE::VARCHAR2)::VARCHAR2(58)
	END::VARCHAR2(30) AS DATA_TYPE,
	CASE
		WHEN NOT A.DEFAULTED
			THEN 'N'
		ELSE 'Y'
	END::VARCHAR2(1) AS DEFAULTED,
	NULL::LONG AS DEFAULT_VALUE,
	NULL::NUMBER AS DEFAULT_LENGTH,
	CASE
		WHEN A.IN_OUT = 'i' OR A.IN_OUT IS NULL
			THEN 'IN'
		WHEN A.IN_OUT = 'o'
			THEN 'OUT'
		WHEN A.IN_OUT = 'b'
			THEN 'IN/OUT'
		ELSE NULL
	END::VARCHAR2(9) AS IN_OUT,
	CASE
		WHEN A.DATA_LENGTH IS NOT NULL
		    THEN A.DATA_LENGTH
		WHEN T.TYPNAME = ANY(ARRAY['int2', 'int4', 'int8',
								   'float4', 'float8',
								   'numeric', 'number'])
			THEN 22
		WHEN T.TYPNAME = ANY(ARRAY['long', 'long_raw'])
			THEN 32760
		ELSE NULL
	END::NUMBER AS DATA_LENGTH,
	CASE
		WHEN A.DATA_PRECISION IS NOT NULL
		    THEN A.DATA_PRECISION
		WHEN T.TYPNAME = ANY(ARRAY['int2', 'int4', 'int8'])
			THEN 38
		WHEN T.TYPNAME = 'float4'
			THEN 63
		WHEN T.TYPNAME = 'float8'
			THEN 126
		WHEN T.TYPNAME = ANY(ARRAY['timestamp', 'timestamptz',
								   'oratimestamp', 'oratimestamptz',
								   'oratimestampltz'])
			THEN 6
		ELSE NULL
	END::NUMBER AS DATA_PRECISION,
	CASE
		WHEN A.DATA_SCALE IS NOT NULL
		    THEN A.DATA_SCALE
		WHEN T.TYPNAME = ANY(ARRAY['float4', 'float8'])
			THEN -127
		ELSE NULL
	END::NUMBER AS DATA_SCALE,
	CASE
		WHEN T.TYPNAME = ANY(ARRAY['numeric', 'number',
								   'int2', 'int4', 'int8',
								   'float4', 'float8'])
			THEN 10
		ELSE NULL
	END::NUMBER AS RADIX,
	CASE
		WHEN T.OID::REGTYPE::VARCHAR2(58) = ANY(ARRAY['char',
													  'character',
													  'varchar2',
													  'clob'])
			THEN 'CHAR_CS'
		WHEN T.OID::REGTYPE::VARCHAR2(58) = ANY(ARRAY['nchar', 'nvarchar2',
													  'nclob'])
			THEN 'NCHAR_CS'
	END::VARCHAR2(44) AS CHARACTER_SET_NAME,
	NULL::VARCHAR2(128) AS TYPE_OWNER,
	CASE
	   WHEN A.TYPE_NAME != '_NULL_'
	        THEN SYS.ORA_CASE_TRANS(A.TYPE_NAME::VARCHAR2)::VARCHAR2(128)
	   ELSE
	        NULL
	END::VARCHAR2(128) AS TYPE_NAME,
	CASE
	   WHEN A.TYPE_SUBNAME != '_NULL_'
	        THEN SYS.ORA_CASE_TRANS(A.TYPE_SUBNAME::VARCHAR2)::VARCHAR2(128)
	   ELSE
	        NULL
	END::VARCHAR2(128) AS TYPE_SUBNAME,
	NULL::VARCHAR2(128) AS TYPE_LINK,
	CASE
	   WHEN A.TYPE_OBJECT_TYPE != '_NULL_'
	        THEN SYS.ORA_CASE_TRANS(A.TYPE_OBJECT_TYPE::VARCHAR2)::VARCHAR2(128)
	   ELSE
	        NULL
	END::VARCHAR2(128) AS TYPE_OBJECT_TYPE,
	CASE
		WHEN (T.TYPTYPE = 'b' OR T.TYPTYPE = 'c') AND A.PLS_TYPE IS NOT NULL
			THEN SYS.ORA_CASE_TRANS(A.PLS_TYPE)
		WHEN T.TYPTYPE = 'b' AND A.PLS_TYPE IS NULL
			THEN SYS.ORA_CASE_TRANS(T.OID::REGTYPE::VARCHAR2)
		WHEN T.TYPTYPE = 'd' AND T.TYPNAME = 'raw'
			THEN 'RAW'
		WHEN T.TYPTYPE = 'd' AND T.TYPNAME = 'blob'
			THEN 'BLOB'
		WHEN T.TYPTYPE = 'd' AND T.TYPNAME = 'clob'
			THEN 'CLOB'
		WHEN T.TYPTYPE = 'd' AND T.TYPNAME = 'nclob'
			THEN 'CLOB'
		WHEN T.TYPTYPE = 'd' AND T.TYPNAME = 'long'
			THEN 'LONG'
		WHEN T.TYPTYPE = 'd' AND T.TYPNAME = 'long_raw'
			THEN 'LONG_RAW'
		ELSE NULL
	END::VARCHAR2(30) AS PLS_TYPE,
	CASE
		WHEN T.OID::REGTYPE::VARCHAR2(58) = ANY(ARRAY['char',
													  'character',
													  'varchar2'])
			THEN NULL
		ELSE 0
	END::NUMBER AS CHAR_LENGTH,
	CASE
		WHEN T.OID::REGTYPE::VARCHAR2(58) = ANY(ARRAY['char',
													  'character',
													  'varchar2'])
			THEN 'B'
		ELSE '0'
	END::VARCHAR2(1) AS CHAR_USED,
	0::VARCHAR2(256) AS ORIGIN_CON_ID,
    A.OWNER_OID AS _OWNER_OID,
    A.NAMESPACE_OID AS _NAMESPACE_OID,
    A.OBJECT_OID AS _OBJECT_OID,
    A.PACKAGE_NAME IS NOT NULL AS _IS_PACKAGE
FROM ARGUMENT_ROWS A
LEFT JOIN PG_CATALOG.PG_TYPE T ON T.OID = A.DATA_TYPE;

