    PID::NUMBER AS SPID,
    USENAME::VARCHAR2(128) AS USERNAME,
    APPLICATION_NAME::VARCHAR2(256) AS PROGRAM,
    BACKEND_TYPE::VARCHAR2(30) AS PNAME,
