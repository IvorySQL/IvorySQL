/* ARGUMENTS' TYPE COUNT */
CREATE OR REPLACE FUNCTION SYS._ORA_ARGS_COUNT(PROID OID)
RETURNS INTEGER
AS $$
DECLARE
	RET INTEGER;
BEGIN
	SELECT
		COUNT(1)
	FROM
	(
		SELECT
			UNNEST(
				CASE
					WHEN PROALLARGTYPES IS NOT NULL
						THEN PROALLARGTYPES
					ELSE PROARGTYPES
				END
			)
		FROM
			PG_PROC
		WHERE OID = $1
	) AS SQ
	INTO
		RET;
	RETURN RET;
END;
$$ LANGUAGE PLPGSQL IMMUTABLE;

/* Parse a package spec's routine signatures into argument rows.
 * Used by DBA/ALL/USER_ARGUMENTS: packaged routines have no pg_proc
 * entries, their signatures only live in pg_package.pkgsrc.
 * FUNCTION|PROCEDURE name [(arg [IN|OUT|IN OUT] type, ...)] [RETURN type];
 * Overloaded declarations get distinct OVERLOAD_IDX values.
 * NB: never compare against '' here - Oracle-mode sessions treat the
 * empty string as NULL.
 */
CREATE OR REPLACE FUNCTION SYS._ORA_PKG_ARGUMENTS(PKGOID OID)
RETURNS TABLE(
	OWNER NAME,
	PACKAGE_NAME NAME,
	OBJECT_NAME TEXT,
	IS_FUNCTION BOOLEAN,
	ARGUMENT_NAME TEXT,
	ARG_POSITION INT,
	IN_OUT TEXT,
	ARG_TYPE TEXT,
	OVERLOAD_IDX INT
) AS $$
DECLARE
	SRC TEXT;
	TAIL TEXT;
	HEAD_M TEXT[];
	SEEN TEXT[];
	KIND TEXT;
	NAM TEXT;
	ARGSTR TEXT;
	RETSTR TEXT;
	ONEARG TEXT;
	W TEXT;
	ARGNAM TEXT;
	MODE VARCHAR2(10);
	REST TEXT;
	TOK TEXT;
	POS INT;
	ARGPOS INT;
	DEPTH INT;
	I INT;
BEGIN
	SELECT PKGSRC INTO SRC FROM PG_CATALOG.PG_PACKAGE WHERE OID = PKGOID;
	IF SRC IS NULL OR LENGTH(TRIM(SRC)) = 0 THEN
		RETURN;
	END IF;

	/* strip comments and collapse whitespace so the spec parses linearly */
	TAIL := REGEXP_REPLACE(SRC, '/\*.*?\*/', ' ', 'g');
	TAIL := REGEXP_REPLACE(TAIL, '--[^\n]*', ' ', 'g');
	TAIL := REGEXP_REPLACE(TAIL, '[[:space:]]+', ' ', 'g');

	SELECT PG_GET_USERBYID(PKGOWNER), PKGNAME
		INTO OWNER, PACKAGE_NAME
		FROM PG_CATALOG.PG_PACKAGE WHERE OID = PKGOID;

	SEEN := ARRAY[]::TEXT[];
	LOOP
		TAIL := LTRIM(TAIL);
		EXIT WHEN TAIL IS NULL OR LENGTH(TAIL) = 0;
		HEAD_M := REGEXP_MATCH(TAIL, '(?i)^(FUNCTION|PROCEDURE) ([A-Za-z_][A-Za-z0-9_$#]*)');
		EXIT WHEN HEAD_M IS NULL;
		KIND := UPPER(HEAD_M[1]);
		NAM := HEAD_M[2];
		SEEN := SEEN || (KIND || ' ' || UPPER(NAM));
		OVERLOAD_IDX := CARDINALITY(ARRAY_POSITIONS(SEEN, KIND || ' ' || UPPER(NAM)));
		TAIL := SUBSTR(TAIL, LENGTH(HEAD_M[1]) + LENGTH(HEAD_M[2]) + 2);

		/* optional parenthesized argument list (nesting-aware) */
		ARGSTR := NULL;
		IF SUBSTRING(LTRIM(TAIL) FROM 1 FOR 1) = '(' THEN
			TAIL := LTRIM(TAIL);
			DEPTH := 0;
			I := 0;
			LOOP
				I := I + 1;
				EXIT WHEN I > LENGTH(TAIL);
				IF SUBSTRING(TAIL FROM I FOR 1) = '(' THEN
					DEPTH := DEPTH + 1;
				ELSIF SUBSTRING(TAIL FROM I FOR 1) = ')' THEN
					DEPTH := DEPTH - 1;
					IF DEPTH = 0 THEN
						ARGSTR := TRIM(SUBSTRING(TAIL FROM 2 FOR I - 2));
						TAIL := SUBSTRING(TAIL FROM I + 1);
						EXIT;
					END IF;
				END IF;
			END LOOP;
		END IF;

		/* optional RETURN type up to the terminating semicolon */
		RETSTR := NULL;
		POS := POSITION(';' IN TAIL);
		IF POS > 0 THEN
			REST := TRIM(SUBSTRING(TAIL FROM 1 FOR POS - 1));
			TAIL := SUBSTRING(TAIL FROM POS + 1);
			IF KIND = 'FUNCTION' THEN
				RETSTR := SUBSTRING(REST FROM '(?i)^RETURN +(.+)$');
			END IF;
		ELSE
			TAIL := '';
		END IF;

		IF KIND = 'FUNCTION' AND RETSTR IS NOT NULL THEN
			OBJECT_NAME := NAM;
			IS_FUNCTION := TRUE;
			ARGUMENT_NAME := NULL;
			ARG_POSITION := 0;
			IN_OUT := 'OUT';
			ARG_TYPE := RETSTR;
			RETURN NEXT;
		END IF;

		IF ARGSTR IS NOT NULL AND LENGTH(ARGSTR) > 0 THEN
			/* split the argument list on top-level commas */
			DEPTH := 0;
			W := '';
			ARGPOS := 0;
			FOR I IN 1 .. LENGTH(ARGSTR) + 1 LOOP
				ONEARG := NULL;		/* NULL marks a split point */
				IF I <= LENGTH(ARGSTR) THEN
					ONEARG := SUBSTRING(ARGSTR FROM I FOR 1);
					IF ONEARG = '(' THEN
						DEPTH := DEPTH + 1;
					ELSIF ONEARG = ')' THEN
						DEPTH := DEPTH - 1;
					END IF;
					IF ONEARG = ',' AND DEPTH = 0 THEN
						ONEARG := NULL;
					ELSE
						W := W || ONEARG;
					END IF;
				END IF;
				IF ONEARG IS NULL THEN
					ONEARG := TRIM(W);
					W := '';
					IF ONEARG IS NOT NULL AND LENGTH(ONEARG) > 0 THEN
						ARGPOS := ARGPOS + 1;
						/* name, then optional mode keywords, rest is the type */
						ARGNAM := SUBSTRING(ONEARG FROM '^([A-Za-z_][A-Za-z0-9_$#]*)');
						REST := TRIM(SUBSTRING(ONEARG FROM LENGTH(ARGNAM) + 1));
						MODE := 'IN';
						LOOP
							IF REST ~* '^IN +OUT\y' THEN
								MODE := 'IN/OUT';
								REST := TRIM(SUBSTRING(REST FROM 7));
							ELSIF REST ~* '^(IN|OUT|INOUT|NOCOPY)\y' THEN
								TOK := UPPER(SUBSTRING(REST FROM '^([A-Za-z]+)'));
								IF TOK <> 'NOCOPY' THEN
									MODE := CASE TOK WHEN 'IN' THEN 'IN'
													WHEN 'OUT' THEN 'OUT'
													ELSE 'IN/OUT' END;
								END IF;
								REST := TRIM(SUBSTRING(REST FROM LENGTH(TOK) + 2));
							ELSE
								EXIT;
							END IF;
						END LOOP;
						/* a spec argument type ends at a DEFAULT or := clause */
						ARG_TYPE := TRIM(SYS.REGEXP_REPLACE(REST, '(?i) +(DEFAULT|:=) .*$', ''));
						OBJECT_NAME := NAM;
						IS_FUNCTION := (KIND = 'FUNCTION');
						ARGUMENT_NAME := ARGNAM;
						ARG_POSITION := ARGPOS;
						IN_OUT := MODE;
						RETURN NEXT;
					END IF;
				END IF;
			END LOOP;
		END IF;
	END LOOP;
END;
$$ LANGUAGE PLPGSQL STABLE;

/* DBA_ARGUMENTS */
CREATE OR REPLACE VIEW SYS.DBA_ARGUMENTS AS
SELECT
	SYS.ORA_CASE_TRANS(
		PG_GET_USERBYID(P.PROOWNER)::VARCHAR2
	)::VARCHAR2(128) AS OWNER,
	SYS.ORA_CASE_TRANS(P.PRONAME::VARCHAR2)::VARCHAR2(128) AS OBJECT_NAME,
	NULL::VARCHAR2(128) AS PACKAGE_NAME,
	P.OID::VARCHAR2(10)::NUMBER AS OBJECT_ID,
	NULL::VARCHAR2(40) AS OVERLOAD,
	1::NUMBER AS SUBPROGRAM_ID,
	SYS.ORA_CASE_TRANS(
		SQ.ARGUMENT_NAME::VARCHAR2
	)::VARCHAR2(128) AS ARGUMENT_NAME,
	SQ.POSITION::NUMBER AS POSITION,
	CASE
		WHEN P.PROKIND = 'f'
			THEN SQ.POSITION + 1
		ELSE SQ.POSITION
	END::NUMBER AS SEQUENCE,
	0::NUMBER AS DATA_LEVEL,
	CASE
		WHEN T.TYPNAME = ANY(ARRAY['int2', 'int4', 'int8',
								   'numeric', 'number'])
			THEN 'NUMBER'
		WHEN T.TYPNAME = ANY(ARRAY['float4', 'float8'])
			THEN 'FLOAT'
		WHEN T.TYPNAME = 'bpchar'
			THEN 'CHAR'
		ELSE ORA_CASE_TRANS(T.OID::REGTYPE::VARCHAR2)::VARCHAR2(58)
	END::VARCHAR2(30) AS DATA_TYPE,
	CASE
		WHEN T.TYPDEFAULT IS NOT NULL
			THEN 'Y'
		ELSE 'N'
	END::VARCHAR2(1) AS DEFAULTED,
	NULL::LONG AS DEFAULT_VALUE,
	NULL::NUMBER AS DEFAULT_LENGTH,
	CASE
		WHEN SQ.IN_OUT = 'i' OR SQ.IN_OUT IS NULL
			THEN 'IN'
		WHEN SQ.IN_OUT = 'o'
			THEN 'OUT'
		WHEN SQ.IN_OUT = 'b'
			THEN 'IN/OUT'
		ELSE NULL
	END::VARCHAR2(9) AS IN_OUT,
	CASE
		WHEN T.TYPNAME = ANY(ARRAY['int2', 'int4', 'int8',
								   'float4', 'float8',
								   'numeric', 'number'])
			THEN 22
		WHEN T.TYPNAME = ANY(ARRAY['long', 'long_raw'])
			THEN 32760
		ELSE NULL
	END::NUMBER AS DATA_LENGTH,
	CASE
		WHEN T.TYPNAME = ANY(ARRAY['int2', 'int4', 'int8'])
			THEN 38
		WHEN T.TYPNAME = 'float4'
			THEN 63
		WHEN T.TYPNAME = 'float8'
			THEN 126
		WHEN T.TYPNAME = ANY(ARRAY['timestamp', 'timestamptz',
								   'oratimestamp', 'oratimestamptz',
								   'oratimestampltz'])
			THEN 6
		ELSE NULL
	END::NUMBER AS DATA_PRECISION,
	CASE
		WHEN T.TYPNAME = ANY(ARRAY['float4', 'float8'])
			THEN -127
		ELSE NULL
	END::NUMBER AS DATA_SCALE,
	CASE
		WHEN T.TYPNAME = ANY(ARRAY['numeric', 'number',
								   'int2', 'int4', 'int8',
								   'float4', 'float8'])
			THEN 10
		ELSE NULL
	END::NUMBER AS RADIX,
	CASE
		WHEN T.OID::REGTYPE::VARCHAR2(58) = ANY(ARRAY['char',
													  'character',
													  'varchar2',
													  'clob'])
			THEN 'CHAR_CS'
		WHEN T.OID::REGTYPE::VARCHAR2(58) = ANY(ARRAY['nchar', 'nvarchar2',
													  'nclob'])
			THEN 'NCHAR_CS'
	END::VARCHAR2(44) AS CHARACTER_SET_NAME,
	NULL::VARCHAR2(128) AS TYPE_OWNER,
	NULL::VARCHAR2(128) AS TYPE_NAME,
	NULL::VARCHAR2(128) AS TYPE_SUBNAME,
	NULL::VARCHAR2(128) AS TYPE_LINK,
	NULL::VARCHAR2(128) AS TYPE_OBJECT_TYPE,
	CASE
		WHEN T.TYPTYPE = 'b'
			THEN SYS.ORA_CASE_TRANS(T.OID::REGTYPE::VARCHAR2)
		WHEN T.TYPTYPE = 'd' AND T.TYPNAME = 'raw'
			THEN 'RAW'
		WHEN T.TYPTYPE = 'd' AND T.TYPNAME = 'blob'
			THEN 'BLOB'
		WHEN T.TYPTYPE = 'd' AND T.TYPNAME = 'clob'
			THEN 'CLOB'
		WHEN T.TYPTYPE = 'd' AND T.TYPNAME = 'nclob'
			THEN 'CLOB'
		WHEN T.TYPTYPE = 'd' AND T.TYPNAME = 'long'
			THEN 'LONG'
		WHEN T.TYPTYPE = 'd' AND T.TYPNAME = 'long_raw'
			THEN 'LONG_RAW'
		ELSE NULL
	END::VARCHAR2(30) AS PLS_TYPE,
	CASE
		WHEN T.OID::REGTYPE::VARCHAR2(58) = ANY(ARRAY['char',
													  'character',
													  'varchar2'])
			THEN NULL
		ELSE 0
	END::NUMBER AS CHAR_LENGTH,
	CASE
		WHEN T.OID::REGTYPE::VARCHAR2(58) = ANY(ARRAY['char',
													  'character',
													  'varchar2'])
			THEN 'B'
		ELSE '0'
	END::VARCHAR2(1) AS CHAR_USED,
	0::VARCHAR2(256) AS ORIGIN_CON_ID
FROM
	PG_PROC AS P
	LEFT JOIN
	(
		SELECT
			OID,
			NULL AS ARGUMENT_NAME,
			PRORETTYPE AS DATA_TYPE,
			'o' AS IN_OUT,
			0 AS POSITION
		FROM
			PG_PROC
		WHERE
			PROKIND = 'f'
		UNION ALL
		SELECT
			OID,
			UNNEST(PROARGNAMES) AS ARGUMENT_NAME,
			UNNEST(
			CASE
				WHEN PROALLARGTYPES IS NOT NULL
					THEN PROALLARGTYPES
				ELSE PROARGTYPES
			END) AS DATA_TYPE,
			UNNEST(PROARGMODES) AS IN_OUT,
			GENERATE_SERIES(1, SYS._ORA_ARGS_COUNT(OID))
		FROM
			PG_PROC
	) AS SQ
		ON P.OID = SQ.OID
	LEFT JOIN PG_TYPE AS T
		ON SQ.DATA_TYPE = T.OID
	LEFT JOIN PG_TRIGGER AS TR
		ON P.OID = TR.TGFOID
WHERE
	TR.OID IS NULL 
	AND P.PRONAMESPACE <> 'PG_CATALOG'::REGNAMESPACE::OID
	AND P.PRONAMESPACE <> 'PG_TOAST'::REGNAMESPACE::OID
	AND P.PRONAMESPACE <> 'INFORMATION_SCHEMA'::REGNAMESPACE::OID
	AND (P.PROKIND = 'f' OR SQ.OID IS NOT NULL)

UNION ALL
SELECT
	SYS.ORA_CASE_TRANS(
		PB.PKG_OWNER::VARCHAR2
	)::VARCHAR2(128) AS OWNER,

	SYS.ORA_CASE_TRANS(PB.OBJECT_NAME::VARCHAR2)::VARCHAR2(128) AS OBJECT_NAME,
	SYS.ORA_CASE_TRANS(PB.PACKAGE_NAME::VARCHAR2)::VARCHAR2(128) AS PACKAGE_NAME,
	PB.PKG_OID::VARCHAR2(10)::NUMBER AS OBJECT_ID,
	PB.OVERLOAD_NO::VARCHAR2(40) AS OVERLOAD,
	1::NUMBER AS SUBPROGRAM_ID,
	SYS.ORA_CASE_TRANS(PB.ARGUMENT_NAME::VARCHAR2)::VARCHAR2(128) AS ARGUMENT_NAME,
	PB.ARG_POSITION::NUMBER AS POSITION,
	CASE
		WHEN PB.IS_FUNCTION
			THEN PB.ARG_POSITION + 1
		ELSE PB.ARG_POSITION
	END::NUMBER AS SEQUENCE,
	0::NUMBER AS DATA_LEVEL,
	CASE
		WHEN SYS.REGEXP_REPLACE(UPPER(TRIM(PB.ARG_TYPE)), '\(.*$', '') = ANY(ARRAY['INT','INTEGER','INT2','INT4','INT8','SMALLINT','BIGINT','NUMBER','NUMERIC','DECIMAL','DEC'])
			THEN 'NUMBER'
		WHEN SYS.REGEXP_REPLACE(UPPER(TRIM(PB.ARG_TYPE)), '\(.*$', '') = ANY(ARRAY['FLOAT','FLOAT4','FLOAT8','REAL','DOUBLE PRECISION','BINARY_DOUBLE','BINARY_FLOAT'])
			THEN 'FLOAT'
		WHEN SYS.REGEXP_REPLACE(UPPER(TRIM(PB.ARG_TYPE)), '\(.*$', '') = ANY(ARRAY['CHAR','NCHAR'])
			THEN 'CHAR'
		WHEN SYS.REGEXP_REPLACE(UPPER(TRIM(PB.ARG_TYPE)), '\(.*$', '') = ANY(ARRAY['VARCHAR','VARCHAR2','NVARCHAR2'])
			THEN 'VARCHAR2'
		WHEN SYS.REGEXP_REPLACE(UPPER(TRIM(PB.ARG_TYPE)), '\(.*$', '') = ANY(ARRAY['CLOB','NCLOB'])
			THEN 'CLOB'
		WHEN SYS.REGEXP_REPLACE(UPPER(TRIM(PB.ARG_TYPE)), '\(.*$', '') = 'BLOB'
			THEN 'BLOB'
		WHEN LEFT(SYS.REGEXP_REPLACE(UPPER(TRIM(PB.ARG_TYPE)), '\(.*$', ''), 9) = 'TIMESTAMP'
			THEN 'TIMESTAMP'
		ELSE UPPER(TRIM(PB.ARG_TYPE))::VARCHAR2(58)
	END::VARCHAR2(30) AS DATA_TYPE,
	'N'::VARCHAR2(1) AS DEFAULTED,
	NULL::LONG AS DEFAULT_VALUE,
	NULL::NUMBER AS DEFAULT_LENGTH,
	PB.IN_OUT::VARCHAR2(9) AS IN_OUT,
	CASE
		WHEN SYS.REGEXP_REPLACE(UPPER(TRIM(PB.ARG_TYPE)), '\(.*$', '') = ANY(ARRAY['NUMBER','NUMERIC','DECIMAL','DEC','INT','INTEGER','INT2','INT4','INT8','SMALLINT','BIGINT','FLOAT','FLOAT4','FLOAT8','REAL','DOUBLE PRECISION','BINARY_DOUBLE','BINARY_FLOAT'])
			THEN 22
		WHEN SYS.REGEXP_REPLACE(UPPER(TRIM(PB.ARG_TYPE)), '\(.*$', '') = ANY(ARRAY['LONG','LONG_RAW'])
			THEN 32760
		ELSE NULL
	END::NUMBER AS DATA_LENGTH,
	CASE
		WHEN SYS.REGEXP_REPLACE(UPPER(TRIM(PB.ARG_TYPE)), '\(.*$', '') = ANY(ARRAY['INT','INTEGER','INT2','INT4','INT8','SMALLINT','BIGINT'])
			THEN 38
		WHEN SYS.REGEXP_REPLACE(UPPER(TRIM(PB.ARG_TYPE)), '\(.*$', '') = 'FLOAT4'
			THEN 63
		WHEN SYS.REGEXP_REPLACE(UPPER(TRIM(PB.ARG_TYPE)), '\(.*$', '') = ANY(ARRAY['FLOAT8','DOUBLE PRECISION','BINARY_DOUBLE'])
			THEN 126
		WHEN LEFT(SYS.REGEXP_REPLACE(UPPER(TRIM(PB.ARG_TYPE)), '\(.*$', ''), 9) = 'TIMESTAMP'
			THEN 6
		ELSE NULL
	END::NUMBER AS DATA_PRECISION,
	CASE
		WHEN SYS.REGEXP_REPLACE(UPPER(TRIM(PB.ARG_TYPE)), '\(.*$', '') = ANY(ARRAY['FLOAT','FLOAT4','FLOAT8','REAL','DOUBLE PRECISION','BINARY_DOUBLE','BINARY_FLOAT'])
			THEN -127
		ELSE NULL
	END::NUMBER AS DATA_SCALE,
	CASE
		WHEN SYS.REGEXP_REPLACE(UPPER(TRIM(PB.ARG_TYPE)), '\(.*$', '') = ANY(ARRAY['NUMBER','NUMERIC','DECIMAL','DEC','INT','INTEGER','INT2','INT4','INT8','SMALLINT','BIGINT','FLOAT','FLOAT4','FLOAT8','REAL','DOUBLE PRECISION','BINARY_DOUBLE','BINARY_FLOAT'])
			THEN 10
		ELSE NULL
	END::NUMBER AS RADIX,
	CASE
		WHEN SYS.REGEXP_REPLACE(UPPER(TRIM(PB.ARG_TYPE)), '\(.*$', '') = ANY(ARRAY['CHAR','CHARACTER','VARCHAR2','CLOB'])
			THEN 'CHAR_CS'
		WHEN SYS.REGEXP_REPLACE(UPPER(TRIM(PB.ARG_TYPE)), '\(.*$', '') = ANY(ARRAY['NCHAR','NVARCHAR2','NCLOB'])
			THEN 'NCHAR_CS'
	END::VARCHAR2(44) AS CHARACTER_SET_NAME,
	NULL::VARCHAR2(128) AS TYPE_OWNER,
	NULL::VARCHAR2(128) AS TYPE_NAME,
	NULL::VARCHAR2(128) AS TYPE_SUBNAME,
	NULL::VARCHAR2(128) AS TYPE_LINK,
	NULL::VARCHAR2(128) AS TYPE_OBJECT_TYPE,
	NULL::VARCHAR2(30) AS PLS_TYPE,
	CASE
		WHEN SYS.REGEXP_REPLACE(UPPER(TRIM(PB.ARG_TYPE)), '\(.*$', '') = ANY(ARRAY['CHAR','CHARACTER','VARCHAR2'])
			THEN NULL
		ELSE 0
	END::NUMBER AS CHAR_LENGTH,
	CASE
		WHEN SYS.REGEXP_REPLACE(UPPER(TRIM(PB.ARG_TYPE)), '\(.*$', '') = ANY(ARRAY['CHAR','CHARACTER','VARCHAR2'])
			THEN 'B'
		ELSE '0'
	END::VARCHAR2(1) AS CHAR_USED,
	0::VARCHAR2(256) AS ORIGIN_CON_ID
FROM
(
	SELECT
		PA.*,
		PG_GET_USERBYID(K.PKGOWNER) AS PKG_OWNER,
		K.OID AS PKG_OID,
		CASE WHEN MAX(PA.OVERLOAD_IDX) OVER (PARTITION BY PA.PACKAGE_NAME, PA.OBJECT_NAME) > 1
			THEN PA.OVERLOAD_IDX
		END AS OVERLOAD_NO
	FROM PG_CATALOG.PG_PACKAGE AS K
		CROSS JOIN LATERAL SYS._ORA_PKG_ARGUMENTS(K.OID) AS PA

) AS PB
ORDER BY
	OWNER, OBJECT_ID
;

